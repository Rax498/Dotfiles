#!/usr/bin/env python3
"""Write eww's colors.scss from the scheme tinty just applied.

Runs as a tinty hook: tinty exports each palette colour as
TINTY_SCHEME_PALETTE_BASE<NN>_HEX_<R|G|B>. The eww styles use Material-style
names ($surface, $primary, ...), so each one is mapped to a Base16 colour
below.
"""
import os
from pathlib import Path

OUT = Path.home() / ".config/eww/colors.scss"


def base(n):
    """Colour of baseNN as an (r, g, b) tuple."""
    key = f"TINTY_SCHEME_PALETTE_BASE{n}_HEX_"
    return tuple(int(os.environ[key + c], 16) for c in "RGB")


def hexs(c):
    return "#%02x%02x%02x" % c


# Material name -> Base16 slot. Only palette colours, no blending.
# Slots follow the Base16 styling guide: 00 background, 01 lighter background,
# 02 selection, 03 comments/borders, 05 foreground, 08 red, 0B green, 0D blue, 0E purple.
SLOTS = {
    # surfaces: base background, then raised layers
    "surface": "00",
    "surface-container-low": "01",
    "surface-container": "01",
    "surface-container-high": "02",
    "surface-container-highest": "03",
    # text and borders
    "on-surface": "05",
    "on-surface-variant": "05",
    "outline": "03",
    "outline-variant": "02",
    # primary
    "primary": "0E",
    "on-primary": "01",
    "primary-container": "02",
    "on-primary-container": "05",
    "primary-fixed-dim": "0E",
    "on-primary-fixed": "01",
    "on-primary-fixed-variant": "02",
    "inverse-primary": "0D",
    # secondary
    "secondary": "0D",
    "on-secondary": "00",
    "secondary-container": "02",
    "on-secondary-container": "05",
    "on-secondary-fixed": "01",
    # tertiary
    "tertiary": "0B",
    "on-tertiary": "00",
    "on-tertiary-container": "05",
    # error
    "error-container": "08",
    "on-error": "00",
    "on-error-container": "00",
}

lines = [f"// Generated by gen-colors.py from {os.environ['TINTY_SCHEME_ID']}. Do not edit."]
lines += [f"${name}: {hexs(base(slot))};" for name, slot in SLOTS.items()]
OUT.write_text("\n".join(lines) + "\n")
