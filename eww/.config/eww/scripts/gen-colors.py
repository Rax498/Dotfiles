#!/usr/bin/env python3
"""Write eww's colors.scss from the scheme tinty just applied.

Runs as a tinty hook: tinty exports each palette colour as
TINTY_SCHEME_PALETTE_BASE<NN>_HEX_<R|G|B>. The eww styles use Material-style
names ($surface, $primary, ...), so each one is mapped to a Base16 colour
below, or to a blend of two.
"""
import os
from pathlib import Path

OUT = Path.home() / ".config/eww/colors.scss"


def base(n):
    """Colour of baseNN as an (r, g, b) tuple."""
    key = f"TINTY_SCHEME_PALETTE_BASE{n}_HEX_"
    return tuple(int(os.environ[key + c], 16) for c in "RGB")


def mix(a, b, t):
    """Blend a toward b by t (0 = a, 1 = b)."""
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def hexs(c):
    return "#%02x%02x%02x" % c


# Accent colours, reused below.
PRIMARY, SECONDARY, TERTIARY, ERROR = base("0E"), base("0D"), base("0B"), base("08")
BG = base("00")

# Material name -> colour.
ROLES = {
    # surfaces: darkest to lightest
    "surface": BG,
    "surface-container-low": base("01"),
    "surface-container": mix(base("01"), base("02"), 0.5),
    "surface-container-high": base("02"),
    "surface-container-highest": mix(base("02"), base("03"), 0.5),
    # text and borders
    "on-surface": base("05"),
    "on-surface-variant": base("04"),
    "outline": base("03"),
    "outline-variant": base("02"),
    # primary
    "primary": PRIMARY,
    "on-primary": BG,
    "primary-container": mix(BG, PRIMARY, 0.35),
    "on-primary-container": base("05"),
    "primary-fixed-dim": PRIMARY,
    "on-primary-fixed": mix(BG, PRIMARY, 0.18),
    "on-primary-fixed-variant": mix(BG, PRIMARY, 0.35),
    "inverse-primary": mix(BG, PRIMARY, 0.65),
    # secondary
    "secondary": SECONDARY,
    "on-secondary": BG,
    "secondary-container": mix(BG, SECONDARY, 0.25),
    "on-secondary-container": base("05"),
    "on-secondary-fixed": mix(BG, SECONDARY, 0.18),
    # tertiary
    "tertiary": TERTIARY,
    "on-tertiary": BG,
    "on-tertiary-container": base("05"),
    # error
    "error-container": mix(BG, ERROR, 0.25),
    "on-error": BG,
    "on-error-container": base("05"),
}

lines = [f"// Generated by gen-colors.py from {os.environ['TINTY_SCHEME_ID']}. Do not edit."]
lines += [f"${name}: {hexs(c)};" for name, c in ROLES.items()]
OUT.write_text("\n".join(lines) + "\n")
